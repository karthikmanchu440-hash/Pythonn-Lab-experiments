# Lab Task B3: Assignment Operators

# Start with score = 50
score = 50
print("Initial score:", score)

score += 10  # score = score + 10
print("After += 10 :", score)

score -= 5   # score = score - 5
print("After -= 5  :", score)

score *= 2   # score = score * 2
print("After *= 2  :", score)

score /= 5   # score = score / 5 (becomes a float)
print("After /= 5  :", score)

score //= 3  # score = score // 3
print("After //= 3 :", score)

score %= 4   # score = score % 4
print("After %= 4  :", score)

score **= 3  # score = score ** 3
print("After **= 3 :", score)
