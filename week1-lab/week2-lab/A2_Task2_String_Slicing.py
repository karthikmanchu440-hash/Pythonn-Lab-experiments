# Lab Task A2.2: String Slicing

full_name = "Jane Doe"

# Extract the first name using slicing
# Slicing from index 0 up to, but not including, index 4
extracted_first_name = full_name[0:4]

print("Full Name:", full_name)
print("Extracted First Name:", extracted_first_name)
